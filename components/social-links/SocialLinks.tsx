export function SocialLinks({
  socials,
  className = "flex items-center gap-5",
  iconClassName = "w-4.5 h-4.5",
}: {
  socials: Business["socials"];
  className?: string;
  iconClassName?: string;
}) {
  const entries = socials
    ? Array.isArray(socials)
      ? []
      : Object.entries(socials).filter(([, url]) => url)
    : [];

  if (entries.length === 0) return null;

  return (
    <div className={className}>
      {entries.map(([platform, url]) => {
        const path = SOCIAL_ICON_PATHS[platform];
        return (
          <a
            key={platform}
            href={url}
            target="_blank"
            rel="noopener noreferrer"
            className="text-stone-500 hover:text-[var(--foreground)] transition-colors"
            aria-label={platform}
          >
            {path ? (
              <svg className={`${iconClassName} fill-current`} viewBox="0 0 24 24">
                <path d={path} />
              </svg>
            ) : (
              <span className="text-xs font-medium capitalize">{platform}</span>
            )}
          </a>
        );
      })}
    </div>
  );
}
